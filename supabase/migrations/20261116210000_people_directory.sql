-- People directory. Additive columns and a rate-history table.
-- shop_trades.bill_rate is filled from default_hourly_rate only where it is
-- still empty, so existing bill rates are not rewritten.
-- admin_users_view is recreated so User Management can show app_metadata.role.
-- That view holds no rows of its own.

alter table public.shop_talent
  add column if not exists email text,
  add column if not exists phone text,
  add column if not exists auth_user_id uuid,
  add column if not exists hire_date date,
  add column if not exists end_date date,
  add column if not exists employment_type text,
  add column if not exists notes text,
  add column if not exists cost_rate numeric,
  add column if not exists bill_rate_override numeric;

do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'shop_talent_auth_user_id_fkey'
  ) then
    alter table public.shop_talent
      add constraint shop_talent_auth_user_id_fkey
      foreign key (auth_user_id) references auth.users (id) on delete set null;
  end if;
end $$;

create index if not exists idx_shop_talent_auth_user_id on public.shop_talent (auth_user_id);

alter table public.shop_trades
  add column if not exists bill_rate numeric,
  add column if not exists default_cost_rate numeric,
  add column if not exists active boolean default true;

update public.shop_trades
set bill_rate = default_hourly_rate
where bill_rate is null
  and default_hourly_rate is not null;

alter table public.talent_skills
  add column if not exists proficiency smallint,
  add column if not exists is_primary boolean default false,
  add column if not exists cert_expires_on date;

do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'talent_skills_proficiency_range'
  ) then
    alter table public.talent_skills
      add constraint talent_skills_proficiency_range
      check (proficiency is null or proficiency between 1 and 4);
  end if;
end $$;

do $$
declare
  talent_type text;
begin
  if to_regclass('public.talent_rate_history') is not null then
    return;
  end if;
  select format_type(a.atttypid, a.atttypmod) into talent_type
  from pg_attribute a
  join pg_class c on c.oid = a.attrelid
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relname = 'shop_talent' and a.attname = 'id' and not a.attisdropped;
  if talent_type is null then
    raise exception 'shop_talent.id is missing; talent_rate_history was not created';
  end if;
  execute format($sql$
    create table public.talent_rate_history (
      id bigint generated by default as identity primary key,
      talent_id %s not null references public.shop_talent (id) on delete cascade,
      cost_rate numeric,
      bill_rate numeric,
      effective_date date not null default current_date,
      created_at timestamptz not null default now()
    )
  $sql$, talent_type);
end $$;

create index if not exists idx_talent_rate_history_talent_id
  on public.talent_rate_history (talent_id, effective_date desc);

create or replace function public.is_ops()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce((
    select
      lower(coalesce(u.raw_app_meta_data->>'role', '')) in ('admin', 'ops')
      or case
           when jsonb_typeof(u.raw_app_meta_data->'is_admin') = 'boolean'
             then (u.raw_app_meta_data->>'is_admin')::boolean
           when lower(coalesce(u.raw_app_meta_data->>'is_admin', '')) in ('true', 't', '1')
             then true
           else false
         end
    from auth.users u
    where u.id = (select auth.uid())
  ), false);
$$;

revoke all on function public.is_ops() from public, anon;
grant execute on function public.is_ops() to authenticated;

drop view if exists public.admin_users_view;
drop function if exists public.admin_users_list();

create function public.admin_users_list()
returns table(
  user_id uuid,
  email text,
  full_name text,
  last_login timestamptz,
  monthly_quota numeric,
  is_manager boolean,
  exclude_from_reporting boolean,
  role text
)
language sql
stable
security definer
set search_path = ''
as $$
  select u.id,
         u.email::text,
         uq.full_name,
         u.last_sign_in_at,
         uq.monthly_quota::numeric,
         coalesce((u.raw_user_meta_data->>'is_manager')::boolean, false),
         coalesce((u.raw_app_meta_data->>'exclude_from_reporting')::boolean, false),
         case
           when coalesce(u.raw_app_meta_data->>'role', '') <> '' then u.raw_app_meta_data->>'role'
           when case
                  when jsonb_typeof(u.raw_app_meta_data->'is_admin') = 'boolean'
                    then (u.raw_app_meta_data->>'is_admin')::boolean
                  when lower(coalesce(u.raw_app_meta_data->>'is_admin', '')) in ('true', 't', '1')
                    then true
                  else false
                end
             then 'admin'
           else 'crew'
         end
  from auth.users u
  left join public.user_quotas uq on u.id = uq.user_id
  where coalesce(public.is_admin(), false);
$$;

revoke all on function public.admin_users_list() from public, anon;
grant execute on function public.admin_users_list() to authenticated;

create view public.admin_users_view with (security_invoker = true) as
  select * from public.admin_users_list();

revoke all on public.admin_users_view from anon, public;
grant select on public.admin_users_view to authenticated;
