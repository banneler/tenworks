-- Optional contacts picked on a deal, copied to project_contacts at launch.
-- Additive: new table only. deal_id and contact_id use the live column types.
-- Signed-in users get the same team-wide access as the other shop tables.
-- Anon gets nothing. No existing rows are rewritten.

do $$
declare
  deal_type text;
  contact_type text;
begin
  select format_type(a.atttypid, a.atttypmod) into deal_type
  from pg_attribute a
  join pg_class c on c.oid = a.attrelid
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relname = 'deals_tw' and a.attname = 'id' and not a.attisdropped;

  select format_type(a.atttypid, a.atttypmod) into contact_type
  from pg_attribute a
  join pg_class c on c.oid = a.attrelid
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relname = 'contacts' and a.attname = 'id' and not a.attisdropped;

  if deal_type is null or contact_type is null then
    raise exception 'deals_tw.id or contacts.id is missing; deal_contacts was not created';
  end if;

  if to_regclass('public.deal_contacts') is null then
    execute format($sql$
      create table public.deal_contacts (
        id bigint generated by default as identity primary key,
        deal_id %s not null references public.deals_tw(id) on delete cascade,
        contact_id %s not null references public.contacts(id) on delete cascade,
        role text not null default 'Client',
        created_at timestamptz not null default now(),
        unique (deal_id, contact_id)
      )
    $sql$, deal_type, contact_type);
  end if;
end $$;

alter table public.deal_contacts enable row level security;

drop policy if exists "Authenticated full access" on public.deal_contacts;
create policy "Authenticated full access"
  on public.deal_contacts
  for all
  to authenticated
  using (true)
  with check (true);

revoke all on table public.deal_contacts from anon;
grant select, insert, update, delete on table public.deal_contacts to authenticated;

create index if not exists idx_deal_contacts_contact_id on public.deal_contacts (contact_id);

do $$
declare
  seq record;
begin
  for seq in
    select sn.nspname, s.relname
    from pg_class s
    join pg_namespace sn on sn.oid = s.relnamespace
    join pg_depend d on d.objid = s.oid and d.deptype in ('a', 'i')
    join pg_class tbl on tbl.oid = d.refobjid
    join pg_namespace tn on tn.oid = tbl.relnamespace
    where s.relkind = 'S'
      and tn.nspname = 'public'
      and tbl.relname = 'deal_contacts'
  loop
    execute format('revoke all on sequence %I.%I from anon', seq.nspname, seq.relname);
    execute format('grant usage, select on sequence %I.%I to authenticated', seq.nspname, seq.relname);
  end loop;
end $$;
